//! The menu-bar item, its settings menu, and the widget's own right-click menu.
//!
//! macOS renders whatever menu was last handed to the status item, so a checkbox
//! built at the wrong moment stays wrong. The menu is rebuilt on every state
//! change *and* when the pointer enters the icon, which is the last moment
//! before a click can open it.

use std::process::Command;
use std::sync::Arc;
use std::time::Duration;

use tauri::image::Image;
use tauri::menu::{CheckMenuItem, Menu, MenuEvent, MenuItem, PredefinedMenuItem, Submenu};
use tauri::tray::{MouseButton, MouseButtonState, TrayIcon, TrayIconBuilder, TrayIconEvent};
use tauri::{AppHandle, Manager};
use tauri_plugin_autostart::ManagerExt;

use crate::state::Core;
use crate::store::Store;
use crate::window::{self, Rect, SKINS, WIDGET};

pub const TRAY_ID: &str = "pear-music-widget";

// Menu-bar template images: 'solid' while connected, 'hollow' when the YouTube
// Music API server cannot be reached — so the menu bar itself tells you whether
// the player is up. Generated by build.rs; @2x so they stay crisp at 18pt.
const SOLID: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/tray-solid@2x.png"));
const HOLLOW: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/tray-hollow@2x.png"));

// The bundle differs between th-ch and pear builds, so the launcher tries each
// name in turn.
const MUSIC_APPS: [&str; 3] = ["YouTube Music", "Pear", "Pear Desktop"];

/// pear-desktop and th-ch's build ship the same appId, so one id covers both.
const MUSIC_APP_ID: &str = "com.github.th-ch.youtube-music";

// Finer steps near the top, because that is the range worth having: below
// about 80% the text starts fighting whatever is behind the glass.
const OPACITIES: [u32; 5] = [100, 95, 90, 85, 80];

/// How strongly the cover's colours wash the card. Stored as a fraction, shown
/// by name — "40%" means nothing to look at, whereas "Subtle" does.
const TINTS: [(u32, &str); 5] = [(0, "Off"), (35, "Subtle"), (60, "Medium"), (80, "Strong"), (100, "Vivid")];

const SKIN_LABELS: [(&str, &str); 2] = [("classic", "Classic"), ("stack", "Stack")];

/// A menu is as wide as its widest item, and the now-playing line is the only
/// one whose length we do not control. Budget it in display columns rather than
/// characters: a CJK title counted by `char` is twice as wide as it looks, which
/// is how a track name ended up stretching the menu halfway across the screen.
/// The rest of the menu tops out around 23 columns ("Quit with YouTube Music").
const NOW_PLAYING_COLUMNS: usize = 36;

/// Display columns a character occupies. An approximation of Unicode's East
/// Asian Width — full-width forms and emoji take two, everything else one —
/// which is all a menu needs.
fn columns(c: char) -> usize {
    let code = c as u32;
    let wide = matches!(code,
        0x1100..=0x115F
        | 0x2E80..=0x303E
        | 0x3041..=0x33FF
        | 0x3400..=0x4DBF
        | 0x4E00..=0x9FFF
        | 0xA000..=0xA4CF
        | 0xAC00..=0xD7A3
        | 0xF900..=0xFAFF
        | 0xFE10..=0xFE19
        | 0xFE30..=0xFE6F
        | 0xFF00..=0xFF60
        | 0xFFE0..=0xFFE6
        | 0x1F300..=0x1F64F
        | 0x1F900..=0x1F9FF
        | 0x20000..=0x3FFFD);
    if wide { 2 } else { 1 }
}

/// Trim to a column budget, leaving room for the ellipsis that says so.
fn ellipsize(text: &str, budget: usize) -> String {
    if text.chars().map(columns).sum::<usize>() <= budget {
        return text.to_string();
    }

    let mut out = String::new();
    let mut used = 0;
    for c in text.chars() {
        let width = columns(c);
        if used + width > budget.saturating_sub(1) {
            break;
        }
        out.push(c);
        used += width;
    }
    out.push('…');
    out
}

fn status_label(status: &str) -> &str {
    match status {
        "connected" => "Connected",
        "connecting" => "Connecting…",
        "offline" => "API server unreachable",
        "unauthorized" => "Not authorised",
        "denied" => "Authorisation denied",
        other => other,
    }
}

pub fn open_music_app() {
    let script = MUSIC_APPS
        .iter()
        .map(|name| format!("open -a \"{name}\""))
        .collect::<Vec<_>>()
        .join(" || ");
    let _ = Command::new("sh").arg("-c").arg(script).spawn();
}

/// Ask the music app to quit, then run `done` — whether or not it worked.
///
/// Addressed by bundle id, not by name: `application "YouTube Music" is running`
/// answers false even while it is running, which silently turns the guard into a
/// no-op. By id it is accurate, and a guarded quit on a closed app does nothing
/// rather than launching it.
///
/// `quit` is an Apple event, so the first use raises the one-time "wants to
/// control" prompt. If that is denied the script just fails and we still quit.
fn quit_music_app_then(app: AppHandle) {
    tauri::async_runtime::spawn(async move {
        let target = format!("application id \"{MUSIC_APP_ID}\"");
        let script = format!("if {target} is running then quit {target}");

        // Never hang the quit on a blocked or slow Apple event.
        let _ = tokio::time::timeout(
            Duration::from_secs(4),
            tokio::task::spawn_blocking(move || {
                let _ = Command::new("osascript").arg("-e").arg(script).output();
            }),
        )
        .await;

        crate::quit(&app);
    });
}

